# ==============================================================================
# Script  : run.ps1 (PowerShell equivalent of run.sh)
# Purpose : Dynamic compilation, simulation, and GTKWave launcher for FPU units
# Usage   :
#   .\run.ps1 adder          -> Simulates param_adder_sub & opens GTKWave
#   .\run.ps1 multiplier     -> Simulates param_multiplier & opens GTKWave
#   .\run.ps1 barrel_shifter -> Simulates barrel_shifter & opens GTKWave
#   .\run.ps1 LZD            -> Simulates leading_zero_detector & opens GTKWave
# ==============================================================================

param (
    [Parameter(Position=0, Mandatory=$false)]
    [string]$Target
)

$ErrorActionPreference = "Stop"

if (-not $Target) {
    Write-Host "=================================================================" -ForegroundColor Yellow
    Write-Host "Error: No target module specified!" -ForegroundColor Red
    Write-Host "Usage: .\run.ps1 <target>"
    Write-Host "Available targets:"
    Write-Host "  .\run.ps1 adder"
    Write-Host "  .\run.ps1 multiplier"
    Write-Host "  .\run.ps1 barrel_shifter"
    Write-Host "  .\run.ps1 LZD"
    Write-Host "================================================================="
    exit 1
}

$T = $Target.ToLower()

switch ($T) {
    { $_ -in "adder", "param_adder_sub", "add" } {
        $RTL = "component/param_adder_sub.v"
        $TB  = "tb/sim_tb/tb_adder.v"
        $VCD = "waveform_adder.vcd"
        $Name = "Parameterized Adder-Subtractor"
    }
    { $_ -in "multiplier", "param_multiplier", "mul" } {
        $RTL = "component/param_multiplier.v"
        $TB  = "tb/sim_tb/tb_multiplier.v"
        $VCD = "waveform_multiplier.vcd"
        $Name = "Parameterized Multiplier"
    }
    { $_ -in "barrel_shifter", "shifter", "barrel" } {
        $RTL = "component/barrel_shifter.v"
        $TB  = "tb/sim_tb/tb_barrel_shifter.v"
        $VCD = "waveform_barrel_shifter.vcd"
        $Name = "Parameterized Barrel Shifter"
    }
    { $_ -in "lzd", "leading_zero_detector" } {
        $RTL = "component/leading_zero_detector.v"
        $TB  = "tb/sim_tb/tb_LZD.v"
        $VCD = "waveform_lzd.vcd"
        $Name = "Leading Zero Detector"
    }
    default {
        Write-Host "Error: Unknown target '$Target'!" -ForegroundColor Red
        Write-Host "Valid targets: adder, multiplier, barrel_shifter, LZD"
        exit 1
    }
}

Write-Host "=================================================================" -ForegroundColor Cyan
Write-Host "Running verification flow for: $Name"
Write-Host "RTL Source : $RTL"
Write-Host "Testbench  : $TB"
Write-Host "Waveform   : $VCD"
Write-Host "================================================================="

Remove-Item -Force -ErrorAction SilentlyContinue $VCD, sim.vvp

# 1. Optional Verilator Lint
$verilatorCmd = Get-Command verilator -ErrorAction SilentlyContinue
if ($verilatorCmd) {
    Write-Host "[STEP 1/3] Running Verilator lint check..." -ForegroundColor Cyan
    & verilator --lint-only -Wall --timing $RTL $TB
    if ($LASTEXITCODE -ne 0) {
        Write-Host "Verilator lint failed!" -ForegroundColor Red
        exit 1
    }
    Write-Host ">> Verilator lint check passed!" -ForegroundColor Green
} else {
    Write-Host "[STEP 1/3] Verilator not found in PATH; skipping Verilator lint." -ForegroundColor DarkGray
}

# 2. Icarus Verilog Compilation
Write-Host "[STEP 2/3] Compiling with Icarus Verilog (iverilog)..." -ForegroundColor Cyan
& iverilog -Wall -g2012 -o sim.vvp $TB $RTL
if ($LASTEXITCODE -ne 0) {
    Write-Host "iverilog compilation failed!" -ForegroundColor Red
    exit 1
}
Write-Host ">> Compilation successful!" -ForegroundColor Green

# 3. Simulation Execution
Write-Host "[STEP 3/3] Running simulation (vvp)..." -ForegroundColor Cyan
& vvp sim.vvp
if ($LASTEXITCODE -ne 0) {
    Write-Host "Simulation execution failed!" -ForegroundColor Red
    exit 1
}
Write-Host ">> Simulation execution completed successfully!" -ForegroundColor Green

# 4. Open GTKWave
if (Test-Path $VCD) {
    Write-Host "=================================================================" -ForegroundColor Cyan
    Write-Host "Opening GTKWave with waveform: $VCD" -ForegroundColor Green
    Write-Host "================================================================="

    $gtkwaveCmd = Get-Command gtkwave -ErrorAction SilentlyContinue
    if (-not $gtkwaveCmd) {
        $gtkwaveCmd = Get-Command "D:\iverilog\gtkwave\bin\gtkwave.exe" -ErrorAction SilentlyContinue
    }

    if ($gtkwaveCmd) {
        Start-Process $gtkwaveCmd.Source -ArgumentList $VCD
    } else {
        Write-Host "Warning: gtkwave executable not found. Waveform saved at $VCD" -ForegroundColor Yellow
    }
} else {
    Write-Host "Error: Waveform file $VCD was not generated by testbench!" -ForegroundColor Red
    exit 1
}

Remove-Item -Force -ErrorAction SilentlyContinue sim.vvp
Write-Host ">> Done!" -ForegroundColor Green
